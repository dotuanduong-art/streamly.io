import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { mkdir } from 'node:fs/promises';
import { createServer } from 'vite';

const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE || 'C:/Users/Admin/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs').href);
process.env.VITE_USE_MOCK = 'true';
process.env.VITE_USE_MOCK_AUTH = 'true';
process.env.VITE_USE_MOCK_USER_DATA = 'true';
const server = await createServer({ server: { host: 'localhost', port: 5181, strictPort: true } });
await server.listen();
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const errors = [];
await mkdir('tests/artifacts', { recursive: true });
try {
  for (const width of [1440, 768, 375]) {
    const context = await browser.newContext({ viewport: { width, height: 900 }, reducedMotion: 'reduce' });
    const page = await context.newPage();
    page.setDefaultTimeout(10000);
    page.setDefaultNavigationTimeout(12000);
    page.on('pageerror', (error) => errors.push(error.message));
    page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
    await context.route(/https:\/\/(picsum\.photos|fonts\.googleapis\.com|fonts\.gstatic\.com)/, (route) => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="500" height="750"><rect width="100%" height="100%" fill="#30323a"/></svg>' }));
    await context.route(/https:\/\/www.youtube.com\//, (route) => route.fulfill({ contentType: 'text/html', body: '<p>Trailer fixture</p>' }));
    await page.goto('http://localhost:5181/');
    await page.getByTestId('hero-more-info-button').waitFor();
    const mobile = width < 768;
    if (mobile) await page.getByRole('button', { name: 'Mở trình đơn', exact: true }).click();
    const toggle = page.getByTestId(mobile ? 'genre-menu-toggle-mobile' : 'genre-menu-toggle');
    await toggle.focus();
    await page.keyboard.press('Enter');
    assert.equal(await toggle.getAttribute('aria-expanded'), 'true');
    await page.keyboard.press('Tab');
    await page.keyboard.press('Escape');
    assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
    assert.equal(await toggle.evaluate((node) => node === document.activeElement), true);
    await toggle.click();
    await page.getByRole('navigation', { name: 'Chọn thể loại', exact: true }).getByRole('menuitem', { name: 'Hành động', exact: true }).click();
    await page.getByRole('heading', { name: 'Hành động', exact: true }).waitFor();
    await page.locator('[data-testid^="movie-card-"]').first().waitFor();
    await page.reload();
    await page.getByRole('heading', { name: 'Hành động', exact: true }).waitFor();
    assert.equal(await page.getByRole('navigation', { name: 'Thể loại', exact: true }).getByRole('link', { name: 'Hành động', exact: true }).getAttribute('aria-current'), 'page');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: `tests/artifacts/genres-${width}.png`, fullPage: true });

    // Create enough local records to exercise actual page boundaries.
    await page.evaluate(() => {
      const date = '2026-10-29T00:00:00Z';
      localStorage.setItem('streamly_mock_movies_created', JSON.stringify(Array.from({ length: 20 }, (_, i) => ({ id: 100 + i, tmdbId: 200000 + i, title: `Phim QA ${i}`, isVisible: true, isFeatured: false, genres: [{ id: 1, name: 'Hành động' }], createdAt: date, updatedAt: date }))));
    });
    await page.reload();
    await page.getByTestId('genre-page-next').click();
    await page.waitForURL('**page=2**');
    const secondPageId = await page.locator('[data-testid^="movie-card-"]').first().getAttribute('data-testid');
    await page.reload();
    await page.locator(`[data-testid="${secondPageId}"]`).waitFor();
    await page.getByTestId('genre-page-prev').click();
    await page.waitForURL('**page=1**');
    await page.goBack();
    await page.waitForURL('**page=2**');
    await page.getByTestId('genre-page-size').selectOption('24');
    await page.waitForURL('**page=1&pageSize=24');
    await page.waitForFunction(() => document.querySelectorAll('[data-testid^="movie-card-"]').length === 24);
    await page.goto('http://localhost:5181/movie/2');
    await page.getByTestId('movie-title').waitFor();
    await page.goto('http://localhost:5181/movie/5');
    await page.getByTestId('movie-title').waitFor();
    assert.equal(await page.getByTestId('watch-trailer-button').isDisabled(), true);
    assert.equal(await page.locator('iframe').count(), 0);
    await page.goto('http://localhost:5181/movie/2');
    await page.getByTestId('movie-title').waitFor();
    const before = await page.getByTestId('watch-button').boundingBox();
    await page.getByRole('button', { name: 'Xem thêm', exact: true }).click();
    await page.getByTestId('modal').waitFor();
    await page.keyboard.press('Escape');
    await page.getByTestId('modal').waitFor({ state: 'detached' });
    assert.deepEqual(await page.getByTestId('watch-button').boundingBox(), before);
    await page.getByTestId('watch-trailer-button').click();
    await page.getByTestId('trailer-modal').waitFor();
    assert.match(await page.locator('iframe').getAttribute('src'), /youtube.com\/embed\/zSWdZVtXT7E/);
    await page.keyboard.press('Escape');
    await page.getByTestId('modal').waitFor({ state: 'detached' });
    await page.getByRole('link', { name: 'Thể loại Khoa học viễn tưởng', exact: true }).click();
    await page.waitForURL('**/genre/2');
    await page.goto('http://localhost:5181/genre/99999');
    await page.getByRole('heading', { name: 'Không tìm thấy thể loại', exact: true }).waitFor();
    await page.goto('http://localhost:5181/genre/1?page=999&pageSize=wrong');
    await page.waitForURL('**page=3&pageSize=12');

    await page.goto('http://localhost:5181/movie/2');
    await page.getByTestId('detail-actions').getByTestId('my-list-button').click();
    await page.waitForURL('**/login');
    await page.getByTestId('login-email').fill('user@streamly.test');
    await page.getByTestId('login-password').fill('Streamly123!');
    await page.getByTestId('login-submit').click();
    await page.waitForURL('**/movie/2');
    await page.getByTestId('detail-actions').getByTestId('my-list-button').click();
    await page.getByTestId('detail-actions').getByRole('button', { name: 'Xóa khỏi danh sách', exact: true }).waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `authenticated nav overflows at ${width}`);
    await page.goto('http://localhost:5181/my-list');
    await page.getByTestId('movie-card-2').waitFor();
    await page.reload();
    await page.getByTestId('movie-card-2').waitFor();
    await page.goto('http://localhost:5181/genre/2');
    await page.getByRole('heading', { name: 'Khoa học viễn tưởng', exact: true }).waitFor();
    await page.getByTestId('search-toggle').click();
    await page.getByTestId('search-input').fill('Interstellar');
    await page.getByTestId('search-suggestion-2').waitFor();
    await page.getByTestId('search-button').click();
    await page.waitForURL('**/search?q=Interstellar');
    await page.getByTestId('movie-card-2').waitFor();
    await page.getByTestId('movie-card-2').click();
    await page.getByTestId('watch-button').click();
    await page.waitForURL('**/watch/2');
    await page.getByRole('button', { name: 'Quay lại', exact: true }).click();
    await page.waitForURL('**/movie/2');
    await page.getByTestId('detail-actions').getByTestId('my-list-button').click();
    await page.getByTestId('detail-actions').getByRole('button', { name: 'Thêm vào danh sách', exact: true }).waitFor();

    await page.goto('http://localhost:5181/');
    const row = page.getByTestId('movie-row-newly-added');
    const viewport = row.locator('.carousel-viewport');
    await viewport.focus();
    const track = viewport.locator(':scope > div');
    const initialTransform = await track.evaluate((node) => getComputedStyle(node).transform);
    await page.keyboard.press('ArrowRight');
    await page.waitForFunction(({ element, before }) => getComputedStyle(element).transform !== before, { element: await track.elementHandle(), before: initialTransform });
    const card = row.locator('.movie-card').first();
    await card.hover({ force: true });
    assert.equal(await card.evaluate((node) => getComputedStyle(node).transform), 'none', 'reduced motion must disable hover scale');
    await page.evaluate(() => localStorage.setItem('streamly_mock_movies_deletions', JSON.stringify(Array.from({ length: 150 }, (_, i) => i + 1))));
    await page.goto('http://localhost:5181/genre/1');
    await page.getByText('Chưa có phim thuộc thể loại Hành động.', { exact: true }).waitFor();

    console.log(`PASS genres/keyboard/paging/refresh/back/trailer/auth/My List/search/watch/Embla/empty/reduced-motion at ${width}px`);
    await context.close();
  }
  assert.deepEqual(errors, [], 'Unexpected browser console errors');
} finally {
  await browser.close();
  await server.close();
}
